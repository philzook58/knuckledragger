"""Run every theorem's JupyterLite cell and record the failures in docs/lite_skip.txt.

Meant for Pyodide, where the cells run:
    node tools/pyodide_smoke.mjs lite/pypi/knuckledragger-*.whl tools/check_lite_cells.py [--write] [modules...]
Stepping (`PTheorem`) cells are also run fully uncommented, as a user stepping to
the end would. sympy is blocked to match the cell's `--no-deps` install.
"""

import contextlib
import io
import sys
import time
from importlib import import_module
from pathlib import Path

sys.modules["sympy"] = None  # type: ignore  # not installed by the cell
sys.path.insert(0, "docs")
from lite_cells import INSTALL, SKIP_FILE, Definitions  # noqa: E402

import kdrag as kd  # noqa: E402
import kdrag.theories  # noqa: E402

write = "--write" in sys.argv
modules = [a for a in sys.argv[1:] if not a.startswith("-")] or [
    ".".join(("kdrag", "theories", *p.with_suffix("").parts)).removesuffix(".__init__")
    for p in sorted(
        q.relative_to(Path(kdrag.theories.__file__).parent)
        for q in Path(kdrag.theories.__file__).parent.rglob("*.py")
    )
]


def run(code: str) -> None:
    code = "\n".join(line for line in code.splitlines() if line != INSTALL)
    with contextlib.redirect_stdout(io.StringIO()):
        exec(compile(code, "<cell>", "exec"), {})


failed = []
total = 0
for module_name in modules:
    try:
        module = import_module(module_name)
        defs = Definitions(module)
    except BaseException as e:  # noqa: BLE001
        print(f"MODULE {module_name}: {type(e).__name__}: {str(e)[:120]}", flush=True)
        failed.append(f"{module_name}  # import: {type(e).__name__}")
        continue
    names = [
        n for n, v in sorted(vars(module).items()) if not n.startswith("_") and isinstance(v, kd.Proof)
    ]
    bad = 0
    t = time.perf_counter()
    for name in names:
        total += 1
        try:
            run(defs.cell(name))
            if name in defs.stepping:
                run(defs.cell(name, stepping=False))
        except BaseException as e:  # noqa: BLE001
            bad += 1
            print(f"  FAIL {module_name}.{name}: {type(e).__name__}: {str(e)[:120]}", flush=True)
            failed.append(f"{module_name}.{name}  # {type(e).__name__}")
    print(f"{module_name}: {len(names) - bad}/{len(names)} ok, {time.perf_counter() - t:.1f}s", flush=True)

print(f"{len(failed)} skipped of {total} theorems")
if write:
    header = "# Generated by tools/check_lite_cells.py: theorems/modules whose cells fail under Pyodide.\n"
    SKIP_FILE.write_text(header + "".join(f + "\n" for f in failed))
    print(f"wrote {SKIP_FILE}")
